_LOOKUP = {code.lower(): code for code, _ in SUPPORTED_LANGUAGES}


def normalize_lang(code: str) -> str | None:
    """Return the canonical code for ``code`` (case-insensitive) or None."""
    return _LOOKUP.get(code.strip().lower())


def codes_overview() -> str:
    """Compact `<code> — name` listing (HTML, sorted by code) for the bot."""
    entries = sorted(SUPPORTED_LANGUAGES, key=lambda item: item[0])
    lines = [f"<code>{code}</code> — {name}" for code, name in entries]
    return "\n".join(lines)
